import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { smokeCaptureDirectory } from './smoke-captures.mjs';
import { createSettingsWorkbench } from './browser-settings-fixture.mjs';
const engine = process.env.CAGE_TEST_BROWSER || 'chromium';
const output = await smokeCaptureDirectory('browser-settings-' + engine);
const f = await createSettingsWorkbench();
const { page, controller, fixtureState, errors } = f;
page.setDefaultTimeout(12000);
const checks = [];
const shot = name => page.screenshot({ path: join(output, name + '.png'), animations: 'disabled' });
try {
  await page.getByRole('button', { name: 'Open browser', exact: true }).click();
  await page.getByRole('button', { name: 'Browser menu', exact: true }).click();
  await page.getByRole('menuitem', { name: 'Settings', exact: true }).click();
  const settings = page.getByRole('region', { name: 'Browser settings', exact: true });
  const nav = settings.getByRole('navigation', { name: 'Browser settings categories' });
  await settings.waitFor();
  const address = settings.getByRole('textbox', { name: 'New tab address', exact: true });
  const nextHome = controller.origin + '/custom';
  await address.fill(nextHome);
  await nav.getByRole('button', { name: 'Appearance', exact: true }).click();
  await nav.getByRole('button', { name: 'New tab', exact: true }).click();
  assert.equal(await address.inputValue(), nextHome, 'switching categories preserves unsaved address');
  fixtureState.failSave = true;
  await settings.getByRole('button', { name: 'Save address', exact: true }).click();
  await settings.getByRole('alert').getByText('Failed to save browser settings. Try again.', { exact: true }).waitFor();
  assert.equal(await address.inputValue(), nextHome);
  fixtureState.failSave = false;
  await settings.getByRole('button', { name: 'Save address', exact: true }).click();
  await settings.getByRole('status').getByText('Saved', { exact: true }).waitFor();
  await shot('new-tab-settings');
  await page.getByRole('button', { name: 'New web page', exact: true }).click();
  await controller.waitFor(async () => (await controller.api('/tabs')).tabs.some(tab => tab.url === nextHome), 'new page uses saved address');
  await page.waitForFunction(url => document.querySelector('.address-bar input')?.value === url, nextHome);
  await page.getByRole('button', { name: 'Browser menu', exact: true }).click();
  await page.getByRole('menuitem', { name: 'Settings', exact: true }).click();
  await settings.waitFor();
  assert.equal(await page.getByRole('tab', { name: 'Settings', exact: true }).count(), 1);
  await nav.getByRole('button', { name: 'Appearance', exact: true }).click();
  const layout = settings.getByRole('combobox', { name: 'Tab bar layout', exact: true });
  await layout.click();
  await settings.getByRole('option', { name: 'Vertical (left)', exact: true }).click();
  await page.getByRole('complementary', { name: 'Vertical tab bar' }).waitFor();
  await page.reload();
  await page.getByRole('button', { name: 'Open browser', exact: true }).click();
  await page.getByRole('complementary', { name: 'Vertical tab bar' }).waitFor();
  await settings.waitFor();
  await nav.getByRole('button', { name: 'New tab', exact: true }).click();
  assert.equal(await address.inputValue(), nextHome);
  checks.push('real menu opens and reuses settings tab; unsaved form survives category changes; save failure retains input; saved default affects new tabs; address and layout survive reload');

  await page.getByRole('button', { name: /^Settings/ }).filter({ has: page.locator('svg') }).first().click();
  const globalSettings = page.getByRole('region', { name: 'Settings', exact: true });
  await globalSettings.waitFor();
  assert.equal(await globalSettings.getByRole('button', { name: 'Browser', exact: true }).count(), 0);
  assert.equal(await globalSettings.getByText('Browser default site', { exact: true }).count(), 0);
  await globalSettings.getByRole('button', { name: 'Back to the workbench', exact: true }).first().click();
  await nav.getByRole('button', { name: 'Extensions', exact: true }).click();
  await settings.getByText('Make the browser work better for you', { exact: true }).waitFor();
  await settings.getByRole('button', { name: 'Import from this computer', exact: true }).click();
  const importer = settings.getByRole('region', { name: 'Import extensions from this computer', exact: true });
  await importer.getByText('Reading Assistant', { exact: true }).waitFor();
  assert.equal(await importer.getByRole('checkbox').nth(1).isDisabled(), true);
  await importer.getByRole('button', { name: 'Select all compatible extensions', exact: true }).click();
  await importer.getByRole('button', { name: 'Import selected extensions (1)', exact: true }).click();
  await importer.getByText('Imported, left disabled', { exact: true }).waitFor();
  await shot('import-results');
  await importer.getByRole('button', { name: 'Done and close', exact: true }).click();
  await importer.waitFor({ state: 'hidden' });
  const enabled = settings.getByRole('checkbox', { name: 'Enable Reading Assistant', exact: true });
  assert.equal(await enabled.isChecked(), false);
  await enabled.click();
  await page.waitForFunction(() => document.querySelector('input[aria-label="Enable Reading Assistant"]')?.checked === true);
  await controller.waitFor(async () => (await controller.api('/extensions', { mode: 'list' })).items.some(item => item.enabled), 'enable imported extension');
  await settings.evaluate(element => { element.scrollTop = 0; });
  await shot('extensions-imported');
  const web = await controller.api('/new', { url: controller.origin + '/import-test' });
  await controller.waitFor(() => controller.evaluate(web.id, 'document.documentElement.dataset.cageSettingsExtension === "active"'), 'imported extension runs');
  await page.getByRole('tab', { name: 'Settings', exact: true }).click();
  await settings.getByRole('button', { name: 'Refresh extensions', exact: true }).click();
  await settings.getByRole('button', { name: 'Remove', exact: true }).click();
  await page.getByRole('dialog', { name: 'Remove this extension?', exact: true }).getByRole('button', { name: 'Remove extension', exact: true }).click();
  await settings.getByText('Make the browser work better for you', { exact: true }).waitFor();
  checks.push('global settings no longer own browser preferences; local import shows per-extension compatibility and permissions, skips legacy extensions, preserves disabled state; enable runs real content script and removal works');

  const file = settings.getByLabel('Choose extension ZIP', { exact: true });
  await file.setInputFiles({ name: 'reading-extension.zip', mimeType: 'application/zip', buffer: f.archive });
  const preview = settings.getByRole('region', { name: 'Confirm extension install', exact: true });
  await preview.getByText('storage', { exact: true }).waitFor();
  await preview.getByRole('button', { name: 'Cancel', exact: true }).click();
  assert.equal((await controller.api('/extensions', { mode: 'list' })).items.length, 0);
  await file.setInputFiles({ name: 'reading-extension.zip', mimeType: 'application/zip', buffer: f.archive });
  await preview.getByRole('button', { name: 'Install extension', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('input[aria-label="Enable Reading Assistant"]')?.checked === true);
  checks.push('ZIP install shows permissions before confirmation; cancel installs nothing; confirming installs the real extension');
  await settings.getByRole('textbox', { name: 'Search browser settings', exact: true }).fill('new tab');
  await address.waitFor();
  await settings.getByRole('textbox', { name: 'Search browser settings', exact: true }).fill('');
  await nav.getByRole('button', { name: 'Appearance', exact: true }).click();
  await page.setViewportSize({ width: 820, height: 558 });
  await shot('minimum-window');
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false);
  await page.setViewportSize({ width: 1280, height: 850 });
  await page.evaluate(() => { document.documentElement.style.zoom = '2'; });
  await settings.getByRole('combobox', { name: 'Browser settings categories', exact: true }).waitFor();
  await settings.getByRole('combobox', { name: 'Tab bar layout', exact: true }).scrollIntoViewIfNeeded();
  await shot('zoom-200');
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false);
  await page.evaluate(() => { document.documentElement.style.zoom = ''; });
  assert.deepEqual(errors, []);
  await writeFile(join(output, 'result.json'), JSON.stringify({ passed: true, engine, checks }, null, 2) + '\n');
  console.log(JSON.stringify({ passed: true, engine, checks }, null, 2));
} catch (error) { await shot('failure'); throw error; }
finally { await f.close(); }
