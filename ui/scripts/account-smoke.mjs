import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { createWorkbench } from './workbench-fixture.mjs';
const output = fileURLToPath(new URL('../../.oil-ui/local-account/shots/', import.meta.url));
await fs.mkdir(output, { recursive: true });
let launchAcks = 0;
const {browser,page,state,errors} = await createWorkbench({nativeRequest: async ({action}) => {
  if (action === 'workbenchReady') { launchAcks++; return true; }
  return null;
}});
await page.exposeFunction('fixtureLaunchAcks', () => launchAcks);
const accountMenu = () => page.getByRole('button', { name: /^Account menu, / });
async function checkMenuLayout() {
  const trigger = accountMenu();
  const settings = page.getByRole('button', { name: 'Settings', exact: true });
  const list = page.getByRole('menu', { name: 'Local account menu' });
  const projects = page.locator('.sidebar-scroll');
  const before = await Promise.all([trigger.boundingBox(), settings.boundingBox(), projects.boundingBox()]);
  await trigger.click();
  const menu = await list.boundingBox();
  assert.ok(menu.y >= 0 && menu.y + menu.height <= before[0].y);
  assert.deepEqual(await trigger.boundingBox(), before[0]);
  assert.deepEqual(await settings.boundingBox(), before[1]);
  const projectBox = await projects.boundingBox();
  assert.ok(projectBox.y + projectBox.height <= menu.y);
  assert.equal(await page.getByRole('menuitem', {name:'Settings',exact:true}).evaluate(el => el === document.activeElement), true);
  await page.keyboard.press('ArrowDown');
  assert.equal(await page.getByRole('menuitem', {name:/Lock Cage/}).evaluate(el => el === document.activeElement), true);
  await page.keyboard.press('Escape');
  await list.waitFor({state:'hidden'});
  assert.equal(await trigger.evaluate(el => el === document.activeElement), true);
  assert.deepEqual(await projects.boundingBox(), before[2]);
}
try {
  Object.assign(state.account, {exists:false,unlocked:false,username:''});
  const previousAcks = launchAcks;
  await page.reload();
  await page.getByRole('heading',{name:'Register a Cage account'}).waitFor();
  await page.waitForFunction(async (previous) => await window.fixtureLaunchAcks() > previous, previousAcks);
  await page.screenshot({path:output+'create.png'});
  await page.getByLabel('Username',{exact:true}).fill('Forest Studio');
  await page.getByLabel('Set password',{exact:true}).fill('fixture-password');
  await page.getByLabel('Confirm password',{exact:true}).fill('fixture-password');
  await page.getByRole('button',{name:'Create local account',exact:true}).click();
  await accountMenu().waitFor();
  await checkMenuLayout();
  await accountMenu().press('Enter');
  await page.screenshot({path:output+'menu.png'});
  await page.keyboard.press('Enter');
  await page.getByRole('heading',{name:'Account',exact:true}).waitFor();
  const groups = page.getByRole('navigation',{name:'Settings groups'});
  await groups.getByRole('button',{name:'General',exact:true}).click();
  await page.getByRole('heading',{name:'Keyboard style',exact:true}).waitFor();
  await groups.getByRole('button',{name:'Account',exact:true}).click();
  await page.getByLabel('Username',{exact:true}).fill('Chickadee Studio');
  await page.getByLabel('Choose avatar image').setInputFiles(fileURLToPath(new URL('../src/logo.png',import.meta.url)));
  state.failAccountSave=true;
  await page.getByRole('button',{name:'Save details',exact:true}).click();
  await page.getByRole('alert').filter({hasText:'Details could not be saved'}).waitFor();
  assert.equal(await page.getByLabel('Username',{exact:true}).inputValue(),'Chickadee Studio');
  assert.equal(state.account.username,'Forest Studio');
  state.failAccountSave=false;
  await page.getByRole('button',{name:'Save details',exact:true}).click();
  await page.getByRole('status').filter({hasText:'Account details saved.'}).waitFor();
  assert.equal(state.account.username,'Chickadee Studio');
  assert.match(state.account.avatar,/^data:image\/png;base64,/);
  await page.screenshot({path:output+'settings.png'});
  await page.getByLabel('Current password',{exact:true}).fill('fixture-password');
  await page.getByLabel('New password',{exact:true}).fill('changed-fixture-password');
  await page.getByLabel('Confirm new password',{exact:true}).fill('changed-fixture-password');
  await page.getByRole('button',{name:'Change password',exact:true}).click();
  await page.getByRole('status').filter({hasText:'Password changed'}).waitFor();
  await page.getByRole('button',{name:'Back to the workbench',exact:true}).click();
  state.status.vm_running=true;state.status.ready=true;
  await page.reload();
  await page.getByRole('button',{name:/^New terminal in .*$/}).click();
  await page.getByRole('menuitem',{name:'Regular terminal',exact:true}).click();
  const ids=state.terminals.map(x=>x.id);
  await accountMenu().click();
  await page.getByRole('menuitem',{name:/Lock Cage/}).click();
  await page.getByRole('region',{name:'Unlock Cage',exact:true}).waitFor();
  assert.equal(state.status.vm_running,true);
  assert.deepEqual(state.terminals.map(x=>x.id),ids);
  await page.getByText('The background environment is still running and tasks have not stopped',{exact:true}).waitFor();
  await page.screenshot({path:output+'locked.png'});
  await page.getByLabel('Account password',{exact:true}).fill('fixture-password');
  await page.getByRole('button',{name:'Unlock Cage',exact:true}).click();
  await page.getByRole('alert').filter({hasText:'Incorrect password'}).waitFor();
  await page.getByLabel('Account password',{exact:true}).fill('changed-fixture-password');
  await page.getByRole('button',{name:'Unlock Cage',exact:true}).click();
  await accountMenu().waitFor();
  assert.deepEqual(state.terminals.map(x=>x.id),ids);
  await page.reload();
  await accountMenu().waitFor();
  assert.match(await accountMenu().getAttribute('aria-label'),/Chickadee Studio/);
  await accountMenu().click();
  await page.getByRole('menuitem',{name:'Settings',exact:true}).click();
  assert.equal(await page.getByLabel('Username',{exact:true}).inputValue(),'Chickadee Studio');
  await page.setViewportSize({width:820,height:558});
  await page.screenshot({path:output+'settings-small.png'});
  await page.getByRole('button',{name:'Back to the workbench',exact:true}).click();
  await checkMenuLayout();
  await accountMenu().click();
  await page.getByRole('menuitem',{name:'Sign out',exact:true}).click();
  await page.getByRole('dialog').getByRole('button',{name:'Stop environment and sign out',exact:true}).click();
  await page.getByRole('region',{name:'Unlock Cage',exact:true}).waitFor();
  assert.equal(state.status.vm_running,false);
  assert.equal(state.terminals.length,0);
  assert.deepEqual(errors,[]);
  console.log('PASS: account creation, avatar/profile persistence, save failure, password change, lock with live terminals, unlock and stop-on-logout');
} finally {await browser.close();}
